# TASK 2: Exploratory Data Analysis (EDA)

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Load the dataset
df = pd.read_csv("products_dataset.csv")

# 1. Ask Meaningful Questions
print("1. MEANINGFUL QUESTIONS")
print("Q1: What is the average product price?")
print("Q2: Which products are the most and least expensive?")
print("Q3: What is the distribution of product prices?")
print("Q4: Are there any duplicate or missing records?")
print("Q5: Is there any relationship between price and reviews?")

# 2. Explore Data Structure
print("\n2. DATA STRUCTURE")
print("Dataset Shape:", df.shape)

print("\nFirst 5 Rows:")
display(df.head())

print("\nColumn Names:")
print(df.columns.tolist())

print("\nData Types:")
print(df.dtypes)

print("\nDataset Information:")
df.info()

# 3. Detect Data Issues
print("\n3. DATA QUALITY CHECK")

print("\nMissing Values:")
print(df.isnull().sum())

print("\nDuplicate Rows:", df.duplicated().sum())

print("\nDuplicate Product Names:",
      df["Product Name"].duplicated().sum())

# Clean Price column
df["Price"] = (
    df["Price"].astype(str)
    .str.replace("$", "", regex=False)
    .str.replace(",", "", regex=False)
    .str.strip()
)

df["Price"] = pd.to_numeric(df["Price"], errors="coerce")

# Clean Reviews column
df["Reviews"] = (
    df["Reviews"].astype(str)
    .str.extract(r"(\d+)")
)

df["Reviews"] = pd.to_numeric(df["Reviews"], errors="coerce")

print("\nInvalid or Missing Prices:", df["Price"].isnull().sum())
print("Invalid or Missing Reviews:", df["Reviews"].isnull().sum())

# 4. Statistical Analysis
print("\n4. STATISTICAL ANALYSIS")

print("\nPrice Statistics:")
print(df["Price"].describe())

print("\nAverage Price:", round(df["Price"].mean(), 2))
print("Median Price:", round(df["Price"].median(), 2))
print("Minimum Price:", df["Price"].min())
print("Maximum Price:", df["Price"].max())

print("\nMost Expensive Products:")
display(df.nlargest(5, "Price")[["Product Name", "Price"]])

print("\nLeast Expensive Products:")
display(df.nsmallest(5, "Price")[["Product Name", "Price"]])

print("\nMost Reviewed Products:")
display(df.nlargest(5, "Reviews")[["Product Name", "Reviews"]])

# 5. Trends, Patterns and Anomalies

# Price distribution
plt.figure(figsize=(8, 5))
sns.histplot(df["Price"].dropna(), bins=10, kde=True)
plt.title("Distribution of Laptop Prices")
plt.xlabel("Price ($)")
plt.ylabel("Number of Products")
plt.tight_layout()
plt.show()

# Identify potential price outliers using IQR
Q1 = df["Price"].quantile(0.25)
Q3 = df["Price"].quantile(0.75)
IQR = Q3 - Q1

lower_limit = Q1 - 1.5 * IQR
upper_limit = Q3 + 1.5 * IQR

outliers = df[
    (df["Price"] < lower_limit) |
    (df["Price"] > upper_limit)
]

print("\nPotential Price Outliers:")
display(outliers[["Product Name", "Price"]])

# Relationship between price and reviews
plt.figure(figsize=(8, 5))
sns.scatterplot(data=df, x="Reviews", y="Price")
plt.title("Relationship Between Price and Reviews")
plt.xlabel("Number of Reviews")
plt.ylabel("Price ($)")
plt.tight_layout()
plt.show()

# 6. Hypothesis Testing
print("\n5. HYPOTHESIS TESTING")

correlation = df["Price"].corr(df["Reviews"])

print("Hypothesis: Product price is related to the number of reviews.")
print("Correlation:", correlation)

if pd.isna(correlation):
    print("Conclusion: Not enough valid data to calculate correlation.")
elif abs(correlation) < 0.3:
    print("Conclusion: Weak linear relationship between price and reviews.")
elif abs(correlation) < 0.7:
    print("Conclusion: Moderate linear relationship between price and reviews.")
else:
    print("Conclusion: Strong linear relationship between price and reviews.")

# Final Summary
print("\n6. FINAL SUMMARY")
print("Total Products:", len(df))
print("Average Price:", round(df["Price"].mean(), 2))
print("Missing Values:\n", df.isnull().sum())
print("Duplicate Rows:", df.duplicated().sum())

