import requests
import pandas as pd
from bs4 import BeautifulSoup

base_url = "https://webscraper.io/test-sites/e-commerce/static/computers/laptops"

headers = {
    "User-Agent": "Mozilla/5.0"
}

data = []

# Visit multiple pages
for page in range(1, 31):

    url = f"{base_url}?page={page}"
    response = requests.get(url, headers=headers, timeout=20)

    print("Page:", page, "| Status:", response.status_code)

    if response.status_code != 200:
        print("Page could not be loaded.")
        break

    soup = BeautifulSoup(response.text, "html.parser")
    products = soup.find_all("div", class_="thumbnail")

    print("Products found:", len(products))

    # Stop if no products are found
    if len(products) == 0:
        break

    for product in products:

        name_tag = product.find("a", class_="title")
        price_tag = product.find("h4", class_="price")
        description_tag = product.find("p", class_="description")
        reviews_tag = product.find("p", class_="review-count")

        name = name_tag.get("title", name_tag.get_text(strip=True)) if name_tag else "N/A"
        price = price_tag.get_text(strip=True) if price_tag else "N/A"
        description = description_tag.get_text(strip=True) if description_tag else "N/A"
        reviews = reviews_tag.get_text(strip=True) if reviews_tag else "N/A"

        data.append([name, price, description, reviews])

# Create dataset
df = pd.DataFrame(
    data,
    columns=["Product Name", "Price", "Description", "Reviews"]
)

# Remove duplicate product records
df = df.drop_duplicates(subset=["Product Name"])

# Save CSV
df.to_csv("products_dataset.csv", index=False, encoding="utf-8-sig")

print("\nDataset saved successfully!")
print("Dataset Shape:", df.shape)
print("\nColumns:")
print(df.columns.tolist())
print("\nFirst 10 rows:")
display(df.head(10))

print("\nMissing Values:")
print(df.isnull().sum())